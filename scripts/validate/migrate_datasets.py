#!/usr/bin/env python3
"""Migrate the legacy datasets/final-v2 layout to the unified CVE-first layout.

Legacy layout (datasets restructure 2026-08-31):
  datasets/final-v2/raw/{attack,normal,baseline}/<CVE>/<variant|workload>/run_XXX_*/
  datasets/final-v2/processed/...        (STALE — do not copy, rebuild instead)
  datasets/final-v2/dataset_manifest.json
  datasets/cross-cve/...                 (incomplete derived set — stage it)

Target layout:
  datasets/raw/<CVE>/{attack,normal,baseline}/<variant|workload>/run_XXX_*/
  datasets/processed/{attack,normal}     (rebuilt by build_pilot_dataset.py)
  datasets/dataset_manifest.json         (template copied from final-v2)
  datasets/_staged_cross_cve/            (old cross-cve, kept not deleted)

Steps:
  1. move datasets/final-v2/raw/<class>/<CVE> -> datasets/raw/<CVE>/<class>
     (a pure rename per (CVE, class); run dirs keep their run_XXX_uuid names)
  2. copy datasets/final-v2/dataset_manifest.json -> datasets/dataset_manifest.json
     as the build template (run_registry/run_counts are regenerated by the build)
  3. stage datasets/cross-cve -> datasets/_staged_cross_cve if present
  4. report per-class/CVE valid counts and the next step.

Usage:
  python3 scripts/validate/migrate_datasets.py --src datasets/final-v2 --dst datasets
"""

import argparse
import json
import shutil
from pathlib import Path

CLASSES = ("attack", "normal", "baseline")


def count_valid(cve_dir):
    return sum(1 for _ in cve_dir.rglob("manifest.json"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", default="datasets/final-v2",
                        help="legacy final-v2 root (source)")
    parser.add_argument("--dst", default="datasets",
                        help="unified datasets root (destination)")
    parser.add_argument("--stage-cross-cve", action="store_true", default=True,
                        help="move datasets/cross-cve -> datasets/_staged_cross_cve")
    args = parser.parse_args()

    src = Path(args.src)
    dst = Path(args.dst)
    src_raw = src / "raw"
    dst_raw = dst / "raw"

    if not (src_raw / "attack").is_dir():
        raise SystemExit(f"source raw/attack not found under {src}")

    (dst_raw).mkdir(parents=True, exist_ok=True)

    # 1. rename per (CVE, class): src_raw/<class>/<CVE> -> dst_raw/<CVE>/<class>
    moved = 0
    for cls in CLASSES:
        class_dir = src_raw / cls
        if not class_dir.is_dir():
            print(f"[migrate] (no raw/{cls})")
            continue
        for cve_dir in sorted(class_dir.iterdir()):
            if not cve_dir.is_dir():
                continue
            target = dst_raw / cve_dir.name / cls
            target.parent.mkdir(parents=True, exist_ok=True)
            if target.exists():
                print(f"[migrate] SKIP {cve_dir.name}/{cls}: {target} already exists")
                continue
            shutil.move(str(cve_dir), str(target))
            moved += 1
            print(f"[migrate] raw/{cls}/{cve_dir.name} -> raw/{cve_dir.name}/{cls}")
    print(f"[migrate] moved {moved} (CVE, class) dirs")

    # 2. copy the final-v2 manifest as the build template
    src_manifest = src / "dataset_manifest.json"
    dst_manifest = dst / "dataset_manifest.json"
    if src_manifest.is_file():
        if dst_manifest.exists():
            print(f"[migrate] SKIP manifest: {dst_manifest} already exists")
        else:
            shutil.copy(str(src_manifest), str(dst_manifest))
            print(f"[migrate] copied manifest template -> {dst_manifest}")
    else:
        print(f"[migrate] (no {src_manifest} — build will create a fresh manifest)")

    # 3. stage the incomplete cross-cve derived set
    cross_cve = dst / "cross-cve"
    if cross_cve.is_dir() and args.stage_cross_cve:
        staged = dst / "_staged_cross_cve"
        if not staged.exists():
            shutil.move(str(cross_cve), str(staged))
            print(f"[migrate] staged {cross_cve} -> {staged}")
        else:
            print(f"[migrate] SKIP staging: {staged} already exists")
    elif cross_cve.is_dir():
        print(f"[migrate] cross-cve left in place (--stage-cross-cve off)")

    # 4. report per-class/CVE valid counts
    print("\n[migrate] raw valid counts after migration:")
    total = 0
    for cve_dir in sorted(d for d in dst_raw.iterdir() if d.is_dir()):
        for cls in CLASSES:
            d = cve_dir / cls
            if d.is_dir():
                v = sum(1 for m in d.rglob("manifest.json")
                        if m.read_text().find('"status": "valid"') >= 0)
                total += v
                print(f"  {cve_dir.name}/{cls}: {v} valid")
    print(f"  TOTAL valid: {total}")

    print("\n[migrate] next step:"
          "\n  python3 scripts/validate/build_pilot_dataset.py --raw datasets/raw --out datasets")
    print("[migrate] then delete datasets/final-v2 (keep it until the rebuild + one train run verify)")


if __name__ == "__main__":
    main()
